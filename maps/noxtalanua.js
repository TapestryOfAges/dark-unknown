function maps_mt_drash_exit7(mapref) {
  mapref.Exit = function(ewho,etomap,efromx,efromy,etox,etoy) {
    console.log("entering Exit");
    if (ewho !== PC) { return; }
    let toname = etomap.getName();
    if (((toname !== "noxtalanua7") && (toname !== "noxtalanua7a") && (toname !== "noxtalanua7b") && (toname !== "noxtalanua7c")) && (this.getName() !== "noxtalanua7")) {
      // not leaving noxtalanua7 (in which case, nothing would need to be done), not going to any noxtalanua7* (in which case, don't reset)
      let destmap = maps.getMap("noxtalanua7");
      let turns = 1;
      if (this.getName() === "noxtalanua7b") { turns = 2; }
      else if (this.getName() === "noxtalanua7a") { turns = 3; }
      let feas = this.features.getAll();
      for (let i=0;i<feas.length;i++) {
        let dest = {destx: feas[i].getx(), desty: feas[i].gety()};
        for (let j=1;j<=turns;j++) {
          dest = Get90DegCoords(13,13,dest.destx,dest.desty);
        }
        MoveBetweenMaps(feas[i],this,destmap,dest.destx,dest.desty);
      }
      
      let npcs = this.npcs.getAll();
      for (let i=0;i<npcs.length;i++) {
        let dest = {destx: npcs[i].getx(), desty: npcs[i].gety()};
        for (let j=1;j<=turns;j++) {
          dest = Get90DegCoords(13,13,dest.destx,dest.desty);
        }
        MoveBetweenMaps(npcs[i],this,destmap,dest.destx,dest.desty);
      }
      
    } 
    console.log("rotated MtD7 back to baseline.");
    return 1;
  }
}

